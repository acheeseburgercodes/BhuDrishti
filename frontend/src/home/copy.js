export const COPY = { en, ne, hi }

const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj)

/** Returns a lookup for landing copy: `c('hero.title')`, with {var} interpolation and English fallback. */
export function makeCopy(lang) {
  const dict = COPY[lang] || en
  return (path, vars) => {
    let value = get(dict, path)
    if (value === undefined) value = get(en, path)
    if (value === undefined) return path
    if (typeof value === 'string' && vars) return value.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`))
    return value
  }
}
